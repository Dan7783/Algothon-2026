def evaluate_ou_series(a: float, eff_c: float, N: int = 30) -> float:
    if a <= 0.0:
        return 1.0e6
    terms = []
    for n in range(N):
        log_num = math.lgamma(n + 0.5) - math.lgamma(0.5) - math.lgamma(n + 1)
        coeff = math.exp(log_num) * (math.sqrt(2.0) * a) ** (2 * n + 1) / (2 * n + 1)
        terms.append(coeff / math.factorial(n))
    return sum(terms) - (a + eff_c)


def get_optimal_z_entry(
    kappa: float,
    sigma: float,
    cost_real: float,
    rule: str = "new",
) -> float:
    if kappa <= 1.0e-12 or sigma <= 1.0e-12:
        return 1.0
    c = cost_real * math.sqrt(2.0 * kappa) / sigma
    eff_c = (c / 2.0) if rule == "new" else c
    try:
        lower = eff_c + 1.0e-5
        upper = max(eff_c + 10.0, 5.0)
        root = root_scalar(
            lambda a: evaluate_ou_series(a, eff_c),
            bracket=[lower, upper],
            method="brentq",
        )
        return float(root.root) if root.converged else max(1.0, eff_c + 0.5)
    except Exception:
        return max(1.0, eff_c + 0.5)


