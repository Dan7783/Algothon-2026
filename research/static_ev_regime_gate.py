#!/usr/bin/env python
"""Causal regime gate between the static EV book and shipped baseline.

The static EV model is fit on 1-500. From day 501 onward, both the EV and
baseline books are marked as shadow portfolios. An EWMA state tracks the
strictly-prior realised net-PnL advantage of EV over baseline:

* positive state -> deploy the EV book;
* negative state -> deploy the baseline;
* both books keep running, so the gate can switch back.

Only EWMA half-life is selected on validation 501-750. OOS is unavailable
unless both fixed validation halves beat the baseline.
"""

from __future__ import annotations

import argparse
import json
import sys
from math import sqrt
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from research import whole_vector_ev_conflicts as study


OUTPUT_DIR = ROOT / "analysis_outputs" / "static_ev_regime_gate"
LOCK_PATH = OUTPUT_DIR / "locked_selection.json"
HALF_LIFE_GRID = (5.0, 10.0, 20.0, 40.0, 80.0)
STATIC_PRIOR = 200.0
STATIC_MIN_EDGE_Z = 0.01
VALIDATION_WINDOWS = (
    ("VAL1", 501, 625),
    ("VAL2", 626, 750),
    ("VALIDATION", 501, 750),
)


def one_step_net_pnl(
    prices: np.ndarray,
    dollars: np.ndarray,
) -> np.ndarray:
    """Net outcome labelled by eval.py score day."""
    outcomes = np.zeros(prices.shape[1] + 1)
    previous_position = np.zeros(dollars.shape[1])
    for history_size in range(1, prices.shape[1]):
        current = prices[:, history_size - 1]
        following = prices[:, history_size]
        position = study._target_shares(
            dollars[history_size],
            current,
        ).astype(float)
        volume = current * np.abs(position - previous_position)
        fee = float(volume @ study.COMMISSION)
        gross = float(position @ (following - current))
        outcomes[history_size + 1] = gross - fee
        previous_position = position
    return outcomes


def gated_targets(
    baseline_dollars: np.ndarray,
    ev_dollars: np.ndarray,
    baseline_outcomes: np.ndarray,
    ev_outcomes: np.ndarray,
    half_life: float,
) -> tuple[np.ndarray, pd.DataFrame]:
    alpha = 1.0 - 0.5 ** (1.0 / half_life)
    gated = baseline_dollars.copy()
    state = 0.0
    records = []

    # EV is the validation-approved default at the beginning of day 501.
    use_ev = True
    for history_size in range(500, len(gated)):
        # At decision h, the outcome labelled h is already observable and was
        # generated by decision h-1. No current/future outcome enters.
        if history_size > 500:
            advantage = (
                ev_outcomes[history_size]
                - baseline_outcomes[history_size]
            )
            state = (1.0 - alpha) * state + alpha * advantage
            use_ev = state >= 0.0

        gated[history_size] = (
            ev_dollars[history_size]
            if use_ev
            else baseline_dollars[history_size]
        )
        records.append(
            {
                "history_size": float(history_size),
                "ewma_advantage": state,
                "use_ev": float(use_ev),
            }
        )
    return gated, pd.DataFrame(records)


def develop() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    prices = study.load_prices(750)
    cache = study.collect_signals(prices)
    pair_calibration, ridge_calibration = study.fit_calibrations(
        cache,
        STATIC_PRIOR,
    )
    ev_dollars, _ = study.ev_dollars(
        cache,
        pair_calibration,
        ridge_calibration,
        STATIC_MIN_EDGE_Z,
    )
    baseline_outcomes = one_step_net_pnl(
        prices,
        cache.baseline_dollars,
    )
    ev_outcomes = one_step_net_pnl(prices, ev_dollars)
    baseline = {
        name: study.region_metrics(
            prices,
            cache.baseline_dollars,
            start,
            end,
        )
        for name, start, end in VALIDATION_WINDOWS
    }

    rows = []
    diagnostics_by_half_life = {}
    for half_life in HALF_LIFE_GRID:
        dollars, diagnostics = gated_targets(
            cache.baseline_dollars,
            ev_dollars,
            baseline_outcomes,
            ev_outcomes,
            half_life,
        )
        diagnostics_by_half_life[half_life] = diagnostics
        record = {"half_life": half_life}
        for name, start, end in VALIDATION_WINDOWS:
            result = study.region_metrics(
                prices,
                dollars,
                start,
                end,
            )
            key = name.lower()
            record[f"{key}_score"] = result["score"]
            record[f"{key}_delta"] = (
                result["score"] - baseline[name]["score"]
            )
        record["robust_delta"] = min(
            record["val1_delta"],
            record["val2_delta"],
        )
        record["ev_usage"] = float(
            diagnostics["use_ev"].mean()
        )
        record["switches"] = float(
            np.sum(np.abs(np.diff(diagnostics["use_ev"])) > 0.0)
        )
        rows.append(record)

    frame = pd.DataFrame(rows).sort_values(
        ["robust_delta", "validation_delta"],
        ascending=False,
    )
    frame.to_csv(OUTPUT_DIR / "development_grid.csv", index=False)
    winner = frame.iloc[0]
    accepted = bool(
        winner["val1_delta"] > 0.0
        and winner["val2_delta"] > 0.0
    )
    winner_half_life = float(winner["half_life"])
    diagnostics_by_half_life[winner_half_life].to_csv(
        OUTPUT_DIR / "selected_gate_history.csv",
        index=False,
    )
    lock = {
        "protocol": {
            "static_calibration_days": [1, 500],
            "selection_days": [501, 750],
            "heldout_days": [751, 1000],
            "promotion_rule": "both 125-day validation halves improve",
        },
        "selected": {"half_life": winner_half_life},
        "accepted_on_validation": accepted,
        "winner": {
            key: float(winner[key])
            for key in winner.index
        },
        "heldout_evaluated": False,
    }
    LOCK_PATH.write_text(json.dumps(lock, indent=2), encoding="utf-8")

    print(frame.to_string(index=False))
    print(f"\nAccepted on validation: {accepted}")
    print("No prices after day 750 were loaded.")


def test() -> None:
    if not LOCK_PATH.exists():
        raise RuntimeError("Run develop first")
    lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
    if not lock["accepted_on_validation"]:
        raise RuntimeError("Validation rejected the gate; OOS stays closed")
    if lock["heldout_evaluated"]:
        raise RuntimeError("Held-out result already recorded")

    prices = study.load_prices(1000)
    cache = study.collect_signals(prices)
    pair_calibration, ridge_calibration = study.fit_calibrations(
        cache,
        STATIC_PRIOR,
    )
    ev_dollars, _ = study.ev_dollars(
        cache,
        pair_calibration,
        ridge_calibration,
        STATIC_MIN_EDGE_Z,
    )
    baseline_outcomes = one_step_net_pnl(
        prices,
        cache.baseline_dollars,
    )
    ev_outcomes = one_step_net_pnl(prices, ev_dollars)
    gated, diagnostics = gated_targets(
        cache.baseline_dollars,
        ev_dollars,
        baseline_outcomes,
        ev_outcomes,
        float(lock["selected"]["half_life"]),
    )
    windows = (
        ("OOS1", 751, 875),
        ("OOS2", 876, 1000),
        ("YEAR4_OOS", 751, 1000),
    )
    result = {"baseline": {}, "gated_ev": {}, "delta": {}}
    for name, start, end in windows:
        baseline = study.region_metrics(
            prices,
            cache.baseline_dollars,
            start,
            end,
        )
        candidate = study.region_metrics(
            prices,
            gated,
            start,
            end,
        )
        result["baseline"][name] = baseline
        result["gated_ev"][name] = candidate
        result["delta"][name] = (
            candidate["score"] - baseline["score"]
        )
        print(
            f"{name:<10} baseline {baseline['score']:9.3f} "
            f"gated {candidate['score']:9.3f} "
            f"delta {result['delta'][name]:+9.3f}"
        )
    result["selected"] = lock["selected"]
    result["oos_ev_usage"] = float(
        diagnostics.loc[
            diagnostics["history_size"] >= 750,
            "use_ev",
        ].mean()
    )
    (OUTPUT_DIR / "heldout_results.json").write_text(
        json.dumps(result, indent=2),
        encoding="utf-8",
    )
    diagnostics.to_csv(
        OUTPUT_DIR / "full_gate_history.csv",
        index=False,
    )
    lock["heldout_evaluated"] = True
    LOCK_PATH.write_text(json.dumps(lock, indent=2), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--phase",
        choices=("develop", "test"),
        required=True,
    )
    args = parser.parse_args()
    if args.phase == "develop":
        develop()
    else:
        test()


if __name__ == "__main__":
    main()
